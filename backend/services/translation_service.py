def translate(key, lang='en'):
    """
    Returns the translation for the specified key and language code.
    Falls back to English or returns the key if not found.
    """
    if not lang:
        lang = 'en'
    lang = lang.lower()[:2] # clean e.g. en_US -> en
    if lang not in LOCALES:
        lang = 'en'
    
    return LOCALES[lang].get(key, LOCALES['en'].get(key, key))
